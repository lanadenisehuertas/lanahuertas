def runs(rows):
    d = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == "#":
                s = x
                while x < len(row) and row[x] == "#":
                    x += 1
                d.append(f"M{s} {y}h{x - s}v1h{s - x}z")
            else:
                x += 1
    return "".join(d)


def grid(name):
    rows = [r for r in ICONS[name].strip("\n").split("\n")]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
    return rows


if sys.argv[1] == "preview":
    from PIL import Image, ImageDraw
    names = list(ICONS)
    S, cols = 8, 8
    W = cols * (16 * S + 24)
    H = ((len(names) + cols - 1) // cols) * (16 * S + 40)
    im = Image.new("RGB", (W, H), (44, 41, 51))
    dr = ImageDraw.Draw(im)
    for i, n in enumerate(names):
        ox = (i % cols) * (16 * S + 24) + 12
        oy = (i // cols) * (16 * S + 40) + 8
        for y, row in enumerate(grid(n)):
            for x, c in enumerate(row):
                if c == "#":
                    dr.rectangle([ox + x * S, oy + y * S, ox + x * S + S - 1, oy + y * S + S - 1], fill=(236, 230, 218))
        dr.text((ox, oy + 16 * S + 6), n, fill=(200, 190, 210))
    # and at real size, 1x and 2x
    im.save("studio-icons.png")
    small = Image.new("RGB", (len(names) * 40 + 20, 60), (44, 41, 51))
    ds = ImageDraw.Draw(small)
    for i, n in enumerate(names):
        for y, row in enumerate(grid(n)):
            for x, c in enumerate(row):
                if c == "#":
                    ds.point((10 + i * 40 + x, 6 + y), fill=(236, 230, 218))
                    ds.rectangle([10 + i * 40 + x * 2, 26 + y * 2, 10 + i * 40 + x * 2 + 1, 26 + y * 2 + 1], fill=(236, 230, 218))
    small.save("studio-icons-small.png")
    print("ok", len(names))
else:
    out = sys.argv[2]
    lines = [
        "/*",
        " * The studio's tool and panel icons: drawn pixel by pixel on a 16px grid,",
        " * like the site's own pixel art (generated from scripts/studio-icons.py).",
        " * Each is one path of 1px runs, kept crisp with shape-rendering.",
        " */",
        "const P = ({ d }: { d: string }) => (",
        '  <svg viewBox="0 0 16 16" width="16" height="16" aria-hidden fill="currentColor" shapeRendering="crispEdges">',
        "    <path d={d} />",
        "  </svg>",
        ");",
        "",
    ]
    for n in ICONS:
        if n == "Eye" or n == "EyeOff":
            continue
        lines.append(f'export const Icon{n} = () => <P d="{runs(grid(n))}" />;')
    lines.append(f'const EYE = "{runs(grid("Eye"))}";')
    lines.append(f'const EYE_OFF = "{runs(grid("EyeOff"))}";')
    lines.append("export const IconEye = ({ off }: { off?: boolean }) => <P d={off ? EYE_OFF : EYE} />;")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", out)

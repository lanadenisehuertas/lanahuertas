"""Palettes and text tones for every slide backdrop.

Run from the repo root:  python -I scripts/extract-palettes.py

For each slug in scripts/backdrops.json writes, to lib/palettes.ts:
  palettes[slug]  five hex colours from the project's key visual (the `ref`),
                  most dominant first — the palette strip on the slide
  tones[slug]     whether the left and right halves of the generated
                  backdrop are dark or light, so text set on that side can
                  switch to light or dark type
"""
import json
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parent.parent
BACKDROPS = REPO / "public" / "art" / "backdrops"


def dist(a, b) -> float:
    return sum((x - y) ** 2 for x, y in zip(a, b)) ** 0.5


def palette(path: Path, n: int = 5) -> list[str]:
    im = Image.open(path).convert("RGB")
    im.thumbnail((160, 160))
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()
    picked: list[tuple[int, int, int]] = []
    for _, idx in sorted(q.getcolors(), reverse=True):
        rgb = tuple(pal[idx * 3: idx * 3 + 3])
        if all(dist(rgb, p) > 48 for p in picked):
            picked.append(rgb)
        if len(picked) == n:
            break
    return ["#%02x%02x%02x" % p for p in picked]


def luminance(im: Image.Image) -> float:
    """Mean relative luminance, 0–1."""
    def lin(c: float) -> float:
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    small = im.convert("RGB").resize((48, 48))
    px = list(small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata())
    return sum(0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b) for r, g, b in px) / len(px)


def tones(path: Path) -> dict[str, str]:
    im = Image.open(path)
    w, h = im.size
    half = {"left": im.crop((0, 0, round(w * 0.45), h)), "right": im.crop((round(w * 0.55), 0, w, h))}
    # 0.18 is roughly where white and ink text reach equal contrast.
    return {side: ("dark" if luminance(part) < 0.18 else "light") for side, part in half.items()}


def main() -> None:
    specs = json.loads((REPO / "scripts" / "backdrops.json").read_text(encoding="utf-8"))
    pal, tone = {}, {}
    for slug, spec in specs.items():
        ref = REPO / "public" / spec["ref"].lstrip("/")
        if ref.exists():
            pal[slug] = palette(ref)
        art = BACKDROPS / f"{slug}.webp"
        if art.exists():
            tone[slug] = tones(art)
    (REPO / "lib" / "palettes.ts").write_text(
        "// Generated by scripts/extract-palettes.py — do not edit by hand.\n"
        "export type Tone = \"dark\" | \"light\";\n\n"
        f"export const palettes: Record<string, string[]> = {json.dumps(pal, indent=2)};\n\n"
        f"export const tones: Record<string, {{ left: Tone; right: Tone }}> = {json.dumps(tone, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"{len(pal)} palettes, {len(tone)} tones -> lib/palettes.ts")


if __name__ == "__main__":
    main()
